print("Operadores de membresia en Python.")

'''Los operadores de pertenencia se utilizan para comprobar si una secuencia esta presente en un objeto.

in  Retorna True si una secuencia con el valor especifico esta presenta en un objeto.

not in Retorna True si una secuencia con el valor no esta presente en el objeto.'''

frutas = ["manzana", "banana", "guinda"]

print("banana" in frutas)

print("anana" not in frutas)

'''Los operadores de pertenencia tambien funcionan con cadenas de caracteres.'''

text = "Hola mundo"
print("H" in text)
print("Hola" in text)
print("z" not in text)



