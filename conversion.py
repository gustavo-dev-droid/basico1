print("Conversion de python.")

'''Si desea especificar un typo para una variable, se puede hacer mediante la conversion de tipos de datos.
La conversion de datos se realiza mediante funciones constructoras.

int() - construye un numero entero a partir de un literal de punto flotante (elimina los decimales) o un literal de cadena(siempre que la cadena represente un numero entero).
float() - contruye un numero de punto flotante a partir de un literal entero de punto flotante o un literal de cadena(siempre que la cadena represente un punnto flotante o un entero).
str() - contruye una cadena a partir de una amplia variedad de tipos de datos, incluyendo cadenas, literales enteros y literales de punto flotante.'''

a=int(1)
b=int(2.8)
c=int("3")

print(a)
print(b)
print(c)

d=float(1)
e=float(2.8)
f=float("3")
g=float("4.2")

print(d)
print(e)
print(f)
print(g)

h=str("s1")
i=str(2)
j=str(3.0)

print(h)
print(i)
print(j)



