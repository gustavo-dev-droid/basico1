print("Operadores aritmeticos de Python.")

'''Los operadores aritmeticos se utilizan con valores numericos para realizar operaciones matematicas comunes.

+  suma             x+y
-  resta            x-y
*  multiplicacion   x*y
/  division         x/y
%  modulo o resto   x%y
** Exponenciacion   x**y
// division entera  x//y'''

x=15
y=4

print(x+y)
print(x-y)
print(x*y)
print(x/y)
print(x%y)
print(x**y)
print(x//y)

'''La division siempre devuelve un numero decimal.
La division entera siempre devuelve un numero entero.'''


