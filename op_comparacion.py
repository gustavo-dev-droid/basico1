print("Operador de comparacion.")

'''Los operadores de comparacion se utilizan para comparar dos valoresa:
==      igual
!=      desigual
>       mayor que
<       menor que
>=      mayor o igual que
<=      menor o igual que

Los operadores de comparacion devuelven True o False en funcion de la comparacion.'''

a = 5
b = 3

print(a == b)
print(a != b)
print(a>b)
print(a<b)
print(a>=b)
print(a>=b)
print(a<=b)

'''Operadores de comparacion de encadenamiento.
Python permite encadenar operadores de comparacion.'''

c=5

print(1 < c < 10)
print(1 < c and c < 4)



