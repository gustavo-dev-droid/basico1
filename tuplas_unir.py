print("Unir dos tuplas en Python.")

'''Para unir dos tuplas o mas puedes usar el operador +.

Ejemplo, unir dos tuplas.'''

tupla1 = ("a", "b", "c")
tupla2 = (1,2,3)
tupla3 = tupla1 + tupla2
print(tupla3)

'''Si deseas multiplicar el contenido de una tupla un numero determinado de veces, puede utilizar el operador +.

Ejemplo, multiplica la tupla de frutas por 2.'''

frutas = ("manzana", "banana", "guinda")
multi_tupla = frutas * 2
print(multi_tupla)




